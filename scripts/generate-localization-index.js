const fs = require("node:fs");
const path = require("node:path");

function getCatalogFiles (directory) {
	const files = fs.readdirSync(directory, { withFileTypes: true })
		.filter(entry => entry.isFile() && /^[a-z]{2,3}(?:-[a-z0-9]{2,8})*\.js$/i.test(entry.name))
		.map(entry => entry.name)
		.sort();
	const catalogs = {};
	for (const file of files) {
		const language = file.slice(0, -3).toLowerCase();
		if (!Object.hasOwn(catalogs, language) || file === `${language}.js`) {
			catalogs[language] = file;
		}
	}
	return catalogs;
}

function generateIndex (directory) {
	return "/* Generated by npm run localization:index. Do not edit manually. */\n/* eslint-disable quote-props */\n"
		+ `globalThis.HoyoLabCatalogFiles = Object.freeze(${JSON.stringify(getCatalogFiles(directory), null, "\t")});\n`;
}

if (require.main === module) {
	const root = path.resolve(__dirname, "..");
	fs.writeFileSync(path.join(root, "setup/config/catalogs.js"), generateIndex(path.join(root, "localization")));
}

module.exports = { getCatalogFiles, generateIndex };
